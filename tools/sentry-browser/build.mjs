// Writes sentry.min.js into each static site's folder. Run with `npm run build`
// here after changing entry.js, the DSN, or updating @sentry/browser.
// The DSN is public by design: it only allows sending errors to this project.
import { build } from 'esbuild';
import { createRequire } from 'module';

const DSN = 'https://bd9f2c2c618bfb1944db9882f400f53a@o4512436636483584.ingest.de.sentry.io/4512443592933456';
const SITES = ['portal', 'crossover_size_converter'];
const { version } = createRequire(import.meta.url)('@sentry/browser/package.json');

for (const site of SITES) {
  await build({
    entryPoints: [new URL('./entry.js', import.meta.url).pathname],
    outfile: new URL(`../../${site}/sentry.min.js`, import.meta.url).pathname,
    bundle: true,
    minify: true,
    format: 'iife',
    target: 'es2020',
    legalComments: 'none',
    define: { __SENTRY_DSN__: JSON.stringify(DSN), __APP_NAME__: JSON.stringify(site) },
    banner: { js: `/* Sentry browser SDK ${version} (MIT license). Generated by tools/sentry-browser/build.mjs: do not edit. */` },
  });
  console.log(`Built ${site}/sentry.min.js with @sentry/browser ${version}`);
}
